/**
 * `completed_at` LIFECYCLE Contract Test
 *
 * THE BUG THIS LOCKS SHUT — handlers/tasks.ts had, in BOTH the single and the bulk path:
 *
 *     if (status === 'completed') updates.push(`completed_at = CURRENT_TIMESTAMP`);
 *
 * Two data-corrupting defects in one line, and no `else` branch:
 *   1. BARE STAMP, not first-write. Re-saving an already-completed task MOVED its
 *      completion timestamp forward, so `completed_at` recorded "when was this last
 *      touched while completed", not "when did it finish". Every cycle-time / lead-time /
 *      throughput number computed off it was silently compressed.
 *   2. NO TRANSITION-OUT CLEAR. completed → todo/in_progress left the stamp in place: a
 *      row simultaneously not-completed and stamped-completed, which every
 *      `WHERE completed_at IS NOT NULL` query counts as done.
 *
 * THE SEMANTIC (ported verbatim from the Command backend, which already had it right —
 * mandrel-command/backend/src/services/task.ts; the two surfaces must AGREE, so this is a
 * port, not a third variant):
 *   → completed:      `completed_at = COALESCE(completed_at, CURRENT_TIMESTAMP)`  (first write wins)
 *   → anything else:  `completed_at = NULL`
 *   → status absent:  completed_at is NOT TOUCHED at all.
 *
 * WHY THE TESTS ARE TRANSITIONS, NOT SAVES: this is a state-machine bug. A test asserting
 * "completing a task sets a timestamp" PASSES against the broken code and proves nothing.
 * The load-bearing assertions here are the ones that FAIL on the pre-fix tree:
 * re-save-leaves-it-UNCHANGED, and transition-out-CLEARS-it. Both are run through the
 * single path AND the bulk path (the twin site is where the class keeps recurring).
 *
 * CLOCK-INDEPENDENCE: the "unchanged" assertions backdate the stamp to a fixed sentinel
 * before re-saving, so they cannot pass by accident on a coarse clock (CURRENT_TIMESTAMP
 * is transaction-scoped; two rapid transactions could otherwise land close enough to make
 * a naive equality check flaky, and a flaky RED makes the GREEN unfalsifiable).
 *
 * Driven through the SAME public path the bridge uses (validate → routeExecutor) — no SQL
 * shortcuts past the tool contract. Direct SQL is used only to SEED and to READ.
 */

import { describe, test, expect, beforeAll, afterAll } from 'vitest';

import { db } from '../config/database.js';
import { validateToolArguments, validationSchemas } from '../middleware/validation.js';
import { routeExecutor } from '../routes/index.js';

// ═══════════════════════════════════════════════════════════════════════════════════════
// THE POPULATION — DERIVED FROM THE TYPE, NOT FROM THE SPEC'S EXAMPLES
// ═══════════════════════════════════════════════════════════════════════════════════════
// The first cut of this file enumerated the statuses the task description happened to name
// (in_progress / todo / cancelled on the single path, in_progress only on bulk). That is the
// author's population, not the product's: `blocked` was never mentioned, so it was never
// tested, and the mutation `else if (status !== 'blocked')` survived the suite green. Worse
// on the bulk side — the ONE transition-out case there was `in_progress`, so narrowing the
// bulk clear to `else if (updates.status === 'in_progress')` also shipped green, and bulk is
// exactly the tool used to bulk-CANCEL (4 of the 6 corrupt prod rows are `cancelled`).
//
// So the population is read off the SAME zod schema the validator enforces — the single
// source that `taskStatusEnum` feeds. Every non-completed member gets a transition-out test
// at BOTH sites, generated by test.each rather than typed out. THAT is why this population is
// whole: it is not a list that has to be maintained alongside the enum, it IS the enum. A
// sixth status becomes a sixth test automatically the moment it is declared — and the
// snapshot assertion below additionally makes the addition (or removal) surface loudly, so
// whoever adds one sees this obligation instead of inheriting a silent hole.
const zodStatusOptions = (tool: string): string[] => {
  // Same ZodEffects unwrap the shipped `declaredParamKeys`/`requiredKeys` use — the schema is
  // wrapped by .refine(), so `.shape` is not on the outer object.
  let schema: any = (validationSchemas as any)[tool];
  while (schema?._def?.typeName === 'ZodEffects') schema = schema._def.schema;
  let field: any = schema.shape.status;
  while (field && typeof field.unwrap === 'function') field = field.unwrap(); // ZodOptional
  return field.options ?? field._def?.values;
};

const SINGLE_STATUSES = zodStatusOptions('task_update');
const BULK_STATUSES = zodStatusOptions('task_bulk_update');
/** Every status that is NOT `completed` — i.e. every transition-OUT that must CLEAR the stamp. */
const SINGLE_CLEARING = SINGLE_STATUSES.filter((s) => s !== 'completed');
const BULK_CLEARING = BULK_STATUSES.filter((s) => s !== 'completed');

const STAMP = Date.now();
const PROJ_NAME = `completed-at-lifecycle-${STAMP}`;
/** A backdated completion far enough in the past that no clock skew can reproduce it. */
const SENTINEL = '2020-01-02T03:04:05.678Z';
let projectId: string;

async function viaPublicTool(toolName: string, rawArgs: any): Promise<any> {
  const validated = validateToolArguments(toolName, rawArgs);
  return routeExecutor(toolName, validated);
}

async function makeTask(status: string): Promise<string> {
  const res = await db.query(
    `INSERT INTO tasks (project_id, title, type, priority, status)
     VALUES ($1, 'completed_at lifecycle fuse', 'general', 'medium', $2)
     RETURNING id`,
    [projectId, status]
  );
  return res.rows[0].id;
}

/** Seed a row that is already completed AND already stamped, at a known past instant. */
async function makeCompletedTaskStampedAt(when: string): Promise<string> {
  const id = await makeTask('completed');
  await db.query(`UPDATE tasks SET completed_at = $2::timestamptz WHERE id = $1`, [id, when]);
  return id;
}

async function readRow(id: string): Promise<{ status: string; completed_at: Date | null }> {
  const res = await db.query(`SELECT status, completed_at FROM tasks WHERE id = $1`, [id]);
  return res.rows[0];
}

const ms = (d: Date | null) => (d === null ? null : d.getTime());

// FILE-scoped fixture: both describe blocks share the project, so setup/teardown must NOT
// sit inside the first describe (its afterAll would delete the project before the bulk
// block ran).
beforeAll(async () => {
  projectId = (
    await db.query(
      `INSERT INTO projects (name, description) VALUES ($1, 'completed_at lifecycle fuse') RETURNING id`,
      [PROJ_NAME]
    )
  ).rows[0].id;
});

afterAll(async () => {
  await db.query(`DELETE FROM tasks WHERE project_id = $1`, [projectId]);
  await db.query(`DELETE FROM projects WHERE id = $1`, [projectId]);
});

describe('the population this file guards', () => {
  // Not a behaviour test — a statement of SCOPE, asserted rather than written in a comment
  // where it could quietly stop being true. If any of these three fail, the transition tables
  // below are no longer covering what the product actually admits.
  test('both task write surfaces advertise the SAME status enum', () => {
    // If bulk ever admitted a status the single path did not (or vice versa), one of the two
    // generated tables would silently stop covering the other site's real input space.
    expect([...BULK_STATUSES].sort()).toEqual([...SINGLE_STATUSES].sort());
  });

  test('the enum is exactly the five known statuses — a sixth must come here first', () => {
    // A SNAPSHOT, deliberately duplicating the enum. Its only job is to fail when someone adds
    // or removes a status, so they read the note at the top of this file and confirm the
    // completed_at semantic for the new state instead of inheriting whatever the `else` does.
    // The tables themselves need no edit — they derive — so this is the *notification*, not
    // the coverage.
    expect([...SINGLE_STATUSES].sort()).toEqual(
      ['blocked', 'cancelled', 'completed', 'in_progress', 'todo'].sort()
    );
  });

  test('every non-completed status is exercised as a transition-out at BOTH sites', () => {
    // Guards the derivation itself: if the unwrap above ever returned undefined/[] (a zod
    // upgrade changing _def shape, say), test.each would generate ZERO cases and the suite
    // would go green having tested nothing. The empty population is the one that slips
    // through, so it is asserted explicitly.
    expect(SINGLE_CLEARING.length).toBe(SINGLE_STATUSES.length - 1);
    expect(SINGLE_CLEARING.length).toBeGreaterThanOrEqual(4);
    expect(BULK_CLEARING.length).toBe(SINGLE_CLEARING.length);
    expect(SINGLE_CLEARING).toContain('cancelled');
    expect(SINGLE_CLEARING).toContain('blocked');
  });
});

describe('completed_at lifecycle — SINGLE path (task_update)', () => {
  test('todo → completed STAMPS completed_at', async () => {
    const id = await makeTask('todo');
    expect(ms((await readRow(id)).completed_at)).toBeNull();

    const before = Date.now();
    const resp = await viaPublicTool('task_update', { projectId, taskId: id, status: 'completed' });
    expect(resp.isError).toBeFalsy();

    const row = await readRow(id);
    expect(row.status).toBe('completed');
    expect(row.completed_at).not.toBeNull();
    // Stamped NOW, not some inherited value (allow generous clock slack either side).
    expect(ms(row.completed_at)!).toBeGreaterThan(before - 60_000);
  });

  test('completed → completed (RE-SAVE) leaves completed_at UNCHANGED — first write wins', async () => {
    // THE ASSERTION THAT FAILED ON THE PRE-FIX TREE. The bare CURRENT_TIMESTAMP moved this
    // stamp from 2020 to now on every re-save.
    const id = await makeCompletedTaskStampedAt(SENTINEL);
    expect(ms((await readRow(id)).completed_at)).toBe(Date.parse(SENTINEL));

    const resp = await viaPublicTool('task_update', { projectId, taskId: id, status: 'completed' });
    expect(resp.isError).toBeFalsy();

    const row = await readRow(id);
    expect(row.status).toBe('completed');
    expect(ms(row.completed_at)).toBe(Date.parse(SENTINEL));
  });

  // THE SECOND ASSERTION THAT FAILED PRE-FIX: there was no `else` branch at all, so a row
  // stayed stamped-completed after moving out of completed. Generated over EVERY non-completed
  // member of the advertised status enum (see "THE POPULATION" at the top) — so the clear can
  // never be narrowed to one status without a test noticing, and a newly-declared status is
  // covered on the day it is declared.
  test.each(SINGLE_CLEARING)('completed → %s CLEARS completed_at to NULL', async (target) => {
    const id = await makeCompletedTaskStampedAt(SENTINEL);

    // a move to `blocked` must now NAME its blocker, so the generated
    // `blocked` case supplies one. The transition under test is unchanged — this adds a
    // field the status move now requires, it does not narrow the population.
    const blockerArg = target === 'blocked' ? { blockedOn: 'agent' } : {};
    const resp = await viaPublicTool('task_update', { projectId, taskId: id, status: target, ...blockerArg });
    expect(resp.isError).toBeFalsy();

    const row = await readRow(id);
    expect(row.status).toBe(target);
    expect(row.completed_at).toBeNull();
  });

  test('in_progress → completed RE-STAMPS fresh (a cleared row stamps again)', async () => {
    const id = await makeTask('in_progress');
    expect(ms((await readRow(id)).completed_at)).toBeNull();

    const before = Date.now();
    const resp = await viaPublicTool('task_update', { projectId, taskId: id, status: 'completed' });
    expect(resp.isError).toBeFalsy();

    const row = await readRow(id);
    expect(row.status).toBe('completed');
    expect(row.completed_at).not.toBeNull();
    expect(ms(row.completed_at)!).toBeGreaterThan(before - 60_000);
    // And emphatically NOT the sentinel/no stale value: COALESCE must not have found one.
    expect(ms(row.completed_at)).not.toBe(Date.parse(SENTINEL));
  });

  // ── The ABSENT population (C3): status not supplied at all ────────────────────────
  test('a status-less update (priority only) does NOT touch completed_at on a completed task', async () => {
    // Guards against a naive fix that hangs `completed_at = NULL` off the wrong scope:
    // if the clear escaped the `status !== undefined` block, editing the priority of a
    // finished task would silently un-finish it.
    const id = await makeCompletedTaskStampedAt(SENTINEL);
    const resp = await viaPublicTool('task_update', { projectId, taskId: id, priority: 'high' });
    expect(resp.isError).toBeFalsy();
    const row = await readRow(id);
    expect(row.status).toBe('completed');
    expect(ms(row.completed_at)).toBe(Date.parse(SENTINEL));
  });

  test('a status-less update does NOT stamp completed_at on a non-completed task', async () => {
    const id = await makeTask('todo');
    const resp = await viaPublicTool('task_update', { projectId, taskId: id, priority: 'high' });
    expect(resp.isError).toBeFalsy();
    expect((await readRow(id)).completed_at).toBeNull();
  });
});

describe('completed_at lifecycle — BULK path (task_bulk_update), the twin site', () => {
  // Same four transitions through bulkUpdateTasks, where the duplicated defect lived. A fix
  // that closes one site and leaves the twin is the failure mode we keep repeating.
  test('todo → completed STAMPS completed_at (bulk)', async () => {
    const a = await makeTask('todo');
    const b = await makeTask('todo');

    const before = Date.now();
    const resp = await viaPublicTool('task_bulk_update', {
      projectId,
      task_ids: [a, b],
      status: 'completed',
    });
    expect(resp.isError).toBeFalsy();

    for (const id of [a, b]) {
      const row = await readRow(id);
      expect(row.status).toBe('completed');
      expect(row.completed_at).not.toBeNull();
      expect(ms(row.completed_at)!).toBeGreaterThan(before - 60_000);
    }
  });

  test('completed → completed (RE-SAVE) leaves completed_at UNCHANGED (bulk)', async () => {
    const a = await makeCompletedTaskStampedAt(SENTINEL);
    const b = await makeCompletedTaskStampedAt(SENTINEL);

    const resp = await viaPublicTool('task_bulk_update', {
      projectId,
      task_ids: [a, b],
      status: 'completed',
    });
    expect(resp.isError).toBeFalsy();

    for (const id of [a, b]) {
      expect(ms((await readRow(id)).completed_at)).toBe(Date.parse(SENTINEL));
    }
  });

  // Generated over EVERY non-completed member of the advertised enum, same as the single path.
  // `cancelled` is the one that matters most in practice: task_bulk_update IS the bulk-cancel
  // tool, and 4 of the 6 corrupt rows measured on prod were cancelled — so the transition that
  // produced most of the real damage was the one the first cut of this file did not exercise.
  test.each(BULK_CLEARING)('completed → %s CLEARS completed_at to NULL (bulk)', async (target) => {
    const a = await makeCompletedTaskStampedAt(SENTINEL);
    const b = await makeCompletedTaskStampedAt(SENTINEL);

    const resp = await viaPublicTool('task_bulk_update', {
      projectId,
      task_ids: [a, b],
      status: target,
      // a `blocked` destination must now NAME its blocker, on the bulk
      // path too. Supplied only for that member, so the generated population is unchanged.
      ...(target === 'blocked' ? { blockedOn: 'agent' } : {}),
    });
    expect(resp.isError).toBeFalsy();

    for (const id of [a, b]) {
      const row = await readRow(id);
      expect(row.status).toBe(target);
      expect(row.completed_at).toBeNull();
    }
  });

  test('in_progress → completed RE-STAMPS fresh (bulk)', async () => {
    const a = await makeTask('in_progress');
    const before = Date.now();
    const resp = await viaPublicTool('task_bulk_update', {
      projectId,
      task_ids: [a],
      status: 'completed',
    });
    expect(resp.isError).toBeFalsy();

    const row = await readRow(a);
    expect(row.completed_at).not.toBeNull();
    expect(ms(row.completed_at)!).toBeGreaterThan(before - 60_000);
  });

  test('a status-less bulk update does NOT touch completed_at (bulk, absent population)', async () => {
    const a = await makeCompletedTaskStampedAt(SENTINEL);
    const resp = await viaPublicTool('task_bulk_update', {
      projectId,
      task_ids: [a],
      priority: 'high',
    });
    expect(resp.isError).toBeFalsy();
    const row = await readRow(a);
    expect(row.status).toBe('completed');
    expect(ms(row.completed_at)).toBe(Date.parse(SENTINEL));
  });
});
